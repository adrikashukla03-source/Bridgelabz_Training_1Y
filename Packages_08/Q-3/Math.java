import static java.lang.Math.*;

public class Math {
    public static void main(String[] args) {
        double x = 16.0;
        double y = 25.0;
        int a = -10;
        int b = 5;
        int c = 3;

        System.out.println("sqrt(16) = " + sqrt(x));    
        System.out.println("pow(2, 3) = " + pow(2, 3)); 
        System.out.println("max(25, 16) = " + max(y, x)); 
        System.out.println("min(3, 5) = " + min(c, b));   
        System.out.println("abs(-10) = " + abs(a));      
    }
}
